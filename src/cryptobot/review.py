"""Review every closed paper trade across all runs, in one compact report.

Reads only each run's `trades` table (small: a few hundred bytes per trade), so it is
safe to run on the 1 GB server beside the paper trader. Wallet variants and the shadow
`labels` variants are reported separately: labels have no wallet limit and buy every
eligible token, so they measure the base rate rather than a strategy.

Usage: uv run python -m cryptobot.review [--root data/paper]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import polars as pl

from cryptobot.m6_report import MIN_TRADES, Z95, _pct, md_cell, md_code, wilson
from cryptobot.paper import PAPER

SHOWN = 10
EXTREMES = 5


def load(root: Path = PAPER) -> tuple[pl.DataFrame | None, list[dict]]:
    """All closed trades with their run name, and each run's summary."""
    frames, runs = [], []
    for run in sorted(p for p in root.iterdir() if p.is_dir()) if root.exists() else []:
        files = sorted((run / "trades").glob("*/*.parquet"))
        if files:
            frames.append(pl.scan_parquet(files).with_columns(run=pl.lit(run.name)).collect())
        summary = run / "summary.json"
        if summary.exists():
            s = json.loads(summary.read_text())
            a, b = s.get("first_event_ms"), s.get("last_event_ms")
            hours = (b - a) / 3_600_000 if a is not None and b is not None else 0.0
            runs.append({"run": run.name, "hours": hours, "trades": s.get("closed_trades", 0)})
    trades = pl.concat(frames, how="diagonal_relaxed") if frames else None
    return trades, runs


def _stats(df: pl.DataFrame, by: list[str]) -> pl.DataFrame:
    return (
        df.group_by(by)
        .agg(
            n=pl.len(),
            wins=(pl.col("pnl_lamports") > 0).sum(),
            mean=pl.col("net_return").mean(),
            sd=pl.col("net_return").std(),
            pnl=pl.col("pnl_lamports").sum(),
        )
        .with_columns(half=Z95 * pl.col("sd").fill_null(0) / pl.col("n").sqrt())
    )


def _row(label: str, n: int, wins: int, mean: float, half: float, pnl: int) -> str:
    lo, hi = wilson(wins, n)
    cells = [
        label,
        f"{n:,}",
        f"{_pct(wins / n)} [{_pct(lo)}-{_pct(hi)}]",
        f"{_pct(mean)} [{_pct(mean - half)} to {_pct(mean + half)}]",
        f"{pnl / 1e9:+.3f}",
    ]
    return "| " + " | ".join(cells) + " |"


HEAD = [
    "| | Trades | Win rate [95% CI] | Mean net return [95% CI] | PnL (SOL) |",
    "|---|---|---|---|---|",
]


def report(trades: pl.DataFrame | None, runs: list[dict]) -> list[str]:
    hours = sum(r["hours"] for r in runs)
    lines = [
        "# Paper trading review: every closed trade",
        "",
        "Generated by `uv run python -m cryptobot.review`. Paper trading only: simulated "
        "fills on live data, fees included, network costs not. Each restart starts a new run "
        "with fresh 1 SOL wallets; trades from every run are pooled here.",
        "",
        f"- Runs: {len(runs)}, covering {hours:,.1f} hours of live data",
    ]
    if trades is None or trades.is_empty():
        return [*lines, "", "No closed trades yet.", ""]
    shadow = pl.col("variant").str.starts_with("labels|")
    wallets, labels = trades.filter(~shadow), trades.filter(shadow)
    lines += [
        f"- Closed trades: {wallets.height:,} by wallet variants, {labels.height:,} by the "
        "shadow labels variants (every eligible token, no wallet limit)",
        "",
        "## Strategy groups (wallet variants)",
        "",
        "Mean net return per trade with a 95% interval on the mean. PnL adds up every "
        "variant's trades in the group, so it is not one wallet's result.",
        "",
        *HEAD,
    ]
    for u, n, w, mean, _sd, pnl, half in _stats(wallets, ["universe"]).sort("mean").rows():
        lines.append(_row(u, n, w, mean, half, pnl))
    ranked = _stats(wallets, ["variant"]).filter(pl.col("n") >= MIN_TRADES).sort("mean")
    positive = ranked.filter(pl.col("mean") > 0).height
    proven = ranked.filter(pl.col("mean") - pl.col("half") > 0).height
    lines += [
        "",
        f"## Variants with at least {MIN_TRADES} trades",
        "",
        f"- {ranked.height} variants; {positive} with a positive mean; {proven} with the 95% "
        "lower bound above zero. With this many variants the best is also the luckiest.",
        "",
        f"Best {SHOWN}:",
        "",
        *HEAD,
    ]
    for v, n, w, mean, _sd, pnl, half in ranked.reverse().head(SHOWN).rows():
        lines.append(_row(md_cell(v), n, w, mean, half, pnl))
    lines += ["", f"Worst {EXTREMES}:", "", *HEAD]
    for v, n, w, mean, _sd, pnl, half in ranked.head(EXTREMES).rows():
        lines.append(_row(md_cell(v), n, w, mean, half, pnl))
    lines += [
        "",
        "## How trades ended (wallet variants)",
        "",
        "`stop` sells at the first price below entry (or the stop level); its mean shows how "
        "far below the level fills land. `quiet` is a token nobody traded for 5 minutes.",
        "",
        *HEAD,
    ]
    for why, n, w, mean, _sd, pnl, half in (
        _stats(wallets, ["exit_reason"]).sort("n").reverse().rows()
    ):
        lines.append(_row(why or "(none)", n, w, mean, half, pnl))
    if not labels.is_empty():
        lines += [
            "",
            "## Base rate: every eligible token (shadow labels)",
            "",
            *HEAD,
        ]
        for v, n, w, mean, _sd, pnl, half in (
            _stats(labels, ["variant"]).sort("mean").reverse().rows()
        ):
            lines.append(_row(md_cell(v), n, w, mean, half, pnl))
    lines += ["", "## Biggest single trades (wallet variants)", ""]
    lines += ["| Net return | Variant | Mint | Exit |", "|---|---|---|---|"]
    by_return = wallets.sort("net_return")
    for frame in (by_return.reverse().head(EXTREMES), by_return.head(EXTREMES)):
        for ret, v, mint, why in frame.select(
            "net_return", "variant", "mint", "exit_reason"
        ).rows():
            lines.append(f"| {_pct(ret)} | {md_cell(v)} | {md_code(mint)} | {why} |")
    lines += ["", "## Runs", "", "| Run | Hours | Closed trades |", "|---|---|---|"]
    lines += [f"| {r['run']} | {r['hours']:.1f} | {r['trades']:,} |" for r in runs]
    return [*lines, ""]


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=PAPER)
    args = parser.parse_args(argv)
    trades, runs = load(args.root)
    print("\n".join(report(trades, runs)))


if __name__ == "__main__":
    main()
